import 'dart:async';
import 'dart:convert';
import 'dart:math';

import 'package:crypto/crypto.dart';

import 'hybrid_cloud_disclosure_consent.dart';
import 'hybrid_progress_checkpoint_journal.dart';

/// Explicit, user-reviewed instructions; never model-internal reasoning.
/// This contract does not authorize any future Cloud dispatch.
final class HybridImmutableStepPlan {
  HybridImmutableStepPlan(List<String> steps)
      : steps = List<String>.unmodifiable(steps) {
    if (steps.isEmpty || steps.length > 1000 ||
        steps.any((s) => s.trim().isEmpty || utf8.encode(s).length > 2048)) {
      throw ArgumentError('Invalid bounded HYBRID plan');
    }
    if (utf8.encode(jsonEncode(steps)).length > 65536) {
      throw ArgumentError('HYBRID plan too large');
    }
  }

  final List<String> steps;

  String instructionFor(int oneBasedStep) {
    if (oneBasedStep < 1 || oneBasedStep > steps.length) {
      throw RangeError.range(oneBasedStep, 1, steps.length);
    }
    return steps[oneBasedStep - 1];
  }
}

/// H49b: immutable protected plan, scoped and verified against H48.
/// No inference/HTTP, no automatic resume, no multi-key atomicity guarantee.
final class HybridImmutableStepPlanStore {
  HybridImmutableStepPlanStore({
    required HybridCloudConsentStorage storage,
    required HybridProgressCheckpointJournal journal,
  }) : _storage = storage, _journal = journal;

  static const _prefix = 'aivexus.hybrid.plan.h49b.';
  static const _secret = 'aivexus.hybrid.plan.h49b.mac';
  static Future<void> _tail = Future<void>.value();

  final HybridCloudConsentStorage _storage;
  final HybridProgressCheckpointJournal _journal;

  Future<T> _serialize<T>(Future<T> Function() operation) {
    final completer = Completer<T>();
    _tail = _tail.then((_) async {
      try {
        completer.complete(await operation());
      } catch (error, stack) {
        completer.completeError(error, stack);
      }
    });
    return completer.future;
  }

  String _key(String owner, String session, String task) =>
      _prefix + sha256.convert(utf8.encode(
          jsonEncode(<String>[owner, session, task]))).toString();

  Future<List<int>> _macKey({required bool create}) async {
    final saved = await _storage.read(_secret);
    if (saved != null) {
      try {
        final key = base64.decode(saved);
        if (key.length == 32) return key;
      } catch (_) { /* invalid protected key: deny */ }
      throw StateError('Invalid protected plan key');
    }
    if (!create) throw StateError('Missing protected plan key');
    final random = Random.secure();
    final key = List<int>.generate(32, (_) => random.nextInt(256));
    await _storage.write(_secret, base64.encode(key));
    return key;
  }

  String _sign(List<int> key, String payload) =>
      Hmac(sha256, key).convert(utf8.encode(payload)).toString();

  bool _sameMac(String a, String b) {
    if (a.length != b.length) return false;
    var mismatch = 0;
    for (var i = 0; i < a.length; i++) {
      mismatch |= a.codeUnitAt(i) ^ b.codeUnitAt(i);
    }
    return mismatch == 0;
  }

  /// Requires the H48 task to exist and have exactly the same step count.
  /// Existing plans cannot be overwritten or regenerated by a model.
  Future<void> save({
    required String ownerId,
    required String sessionId,
    required String taskId,
    required HybridImmutableStepPlan plan,
  }) => _serialize(() async {
    final state = await _journal.load(
      ownerId: ownerId, sessionId: sessionId, taskId: taskId);
    if (state == null || state.totalSteps != plan.steps.length) {
      throw StateError('Missing or mismatched H48 task');
    }
    final key = _key(ownerId, sessionId, taskId);
    final payload = jsonEncode(<String, Object>{
      'version': 1,
      'scope': key,
      'steps': plan.steps,
    });
    final secret = await _macKey(create: true);
    final envelope = jsonEncode(<String, String>{
      'payload': payload,
      'mac': _sign(secret, payload),
    });
    final previous = await _storage.read(key);
    if (previous != null) {
      // Fail closed on tampering and any attempt to rewrite existing plans.
      if (previous != envelope) {
        throw StateError('HYBRID plan is immutable or damaged');
      }
      return;
    }
    await _storage.write(key, envelope);
    if (await _storage.read(key) != envelope) {
      throw StateError('Protected plan readback failed');
    }
  });

  /// Never triggers inference and only returns instructions for this scope.
  Future<HybridImmutableStepPlan?> load({
    required String ownerId,
    required String sessionId,
    required String taskId,
  }) => _serialize(() async {
    final state = await _journal.load(
      ownerId: ownerId, sessionId: sessionId, taskId: taskId);
    if (state == null) return null;
    final key = _key(ownerId, sessionId, taskId);
    final raw = await _storage.read(key);
    if (raw == null) return null;
    try {
      final envelope = jsonDecode(raw);
      if (envelope is! Map<String, dynamic>) return null;
      final payload = envelope['payload'];
      final signature = envelope['mac'];
      if (payload is! String || signature is! String ||
          utf8.encode(payload).length > 65536) return null;
      final secret = await _macKey(create: false);
      if (!_sameMac(_sign(secret, payload), signature)) return null;
      final data = jsonDecode(payload);
      if (data is! Map<String, dynamic> ||
          data['version'] != 1 || data['scope'] != key ||
          data['steps'] is! List) return null;
      final rawSteps = data['steps'] as List;
      if (rawSteps.any((s) => s is! String)) return null;
      final plan = HybridImmutableStepPlan(rawSteps.cast<String>());
      if (state.totalSteps != plan.steps.length) return null;
      return plan;
    } catch (_) {
      return null;
    }
  });
}
